CREATE TABLE pedidos (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado VARCHAR(40) NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_cancelacion TIMESTAMP WITH TIME ZONE
);

CREATE TABLE pedido_detalles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INTEGER NOT NULL REFERENCES pedidos(id_pedido),
    kit_id INTEGER NOT NULL CHECK (kit_id > 0),
    kit_articulo_id INTEGER NOT NULL CHECK (kit_articulo_id > 0),
    cantidad NUMERIC(12,3) NOT NULL CHECK (cantidad > 0),
    CONSTRAINT uq_pedido_detalle_referencia UNIQUE (pedido_id, kit_id, kit_articulo_id)
);

CREATE INDEX idx_pedidos_fecha ON pedidos(fecha_creacion, id_pedido);
